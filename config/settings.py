# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def is_placeholder_database_url(value):
    if not value:
        return True

    lowered = value.lower()
    placeholders = ['user', 'password', 'host', 'database']
    normalized = re.sub(r'[^a-z0-9]+', '', lowered)
    return any(token in normalized for token in placeholders)


DATABASE_URL = os.environ.get('DATABASE_URL') or os.environ.get('database')
